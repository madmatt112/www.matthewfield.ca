import type { NextConfig } from "next";
import {
  BLOG_DRAFT_LEAK_GUARD_MSG_PREVIEW,
  BLOG_DRAFT_LEAK_GUARD_MSG_PRODUCTION,
  checkVercelDraftGuard,
} from "./src/lib/blog-errors";

/*
 * Early-stderr env-var-scoping guard (Operator-error UX Layer 1).
 *
 * Runs at module top level before any Next.js prerender wrapper. If the
 * Vercel build env reflects a draft-leak misconfiguration, write the named
 * diagnostic to stderr and exit non-zero — this surfaces at a log layer
 * Vercel is less likely to re-format than the deeper getPublishedPosts()
 * rethrow path. Local dev (VERCEL unset) is unaffected.
 *
 * Source-of-truth for the error message bodies and the underlying check:
 *   src/lib/blog-errors.ts
 *
 * Fix (Vercel UI): Project Settings → Environment Variables → ensure
 *   BLOG_INCLUDE_DRAFTS is set on Preview scope only (NOT Production).
 *
 * See Req 7.3 in .spec-workflow/specs/blog-core/requirements.md and the
 * design.md "Operator-error UX" + "next.config.ts (extension)" sections.
 */
const __draftGuard = checkVercelDraftGuard();
if (__draftGuard?.kind === "production") {
  process.stderr.write(BLOG_DRAFT_LEAK_GUARD_MSG_PRODUCTION + "\n");
  process.exit(1);
}
if (__draftGuard?.kind === "preview") {
  process.stderr.write(BLOG_DRAFT_LEAK_GUARD_MSG_PREVIEW + "\n");
  process.exit(1);
}

const cspDirectives = [
  "default-src 'self'",
  // `'wasm-unsafe-eval'` is required by Pagefind's WebAssembly index runtime
  // loaded by <SiteSearch /> via dynamic import of /pagefind/pagefind.js.
  // Without it, the search dialog's WASM instantiation throws a CSP error
  // and Pagefind cannot return results. Scoped to script-src only — does
  // not allow eval() in JavaScript.
  "script-src 'self' 'unsafe-inline' 'wasm-unsafe-eval'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "frame-src 'self'",
  "connect-src 'self'",
  "form-action 'self'",
].join("; ");

const nextConfig: NextConfig = {
  headers: async () => {
    const routes = [
      {
        source: "/((?!playground(?:/|$)).*)",
        headers: [
          {
            key: "Content-Security-Policy",
            value: cspDirectives,
          },
        ],
      },
    ];
    if (process.env.VERCEL_ENV === "preview") {
      routes.push({
        source: "/(.*)",
        headers: [
          {
            key: "X-Robots-Tag",
            value: "noindex, nofollow",
          },
        ],
      });
    }

    /*
     * Hidden-post defensive `X-Robots-Tag` (Req 7.4, 7.11).
     *
     * Policy: applies to posts with `hiddenFromLists === true` ONLY,
     * regardless of `excludeFromSearch` (per blog-enhanced design v4 §1
     * fourth bullet). `excludeFromSearch` governs Pagefind indexing only;
     * search-engine visibility is gated by `hiddenFromLists`.
     *
     * Defense-in-depth alongside the per-page `<meta name="robots">` tag —
     * bots parsing headers but not HTML still see noindex.
     *
     * The Velite output (`./.velite/index.js`) is generated by `pnpm build`
     * and may be absent on a fresh checkout. Wrap the import in try/catch
     * with an empty-array fallback so `next build` succeeds even before
     * Velite has run.
     */
    let hiddenRoutes: string[] = [];
    try {
      const { posts } = (await import("./.velite/index.js")) as {
        posts: Array<{ slug: string; draft?: boolean; hiddenFromLists?: boolean }>;
      };
      hiddenRoutes = posts
        .filter((p) => p.hiddenFromLists === true && !p.draft)
        .map((p) => `/blog/${p.slug}`);
    } catch {
      hiddenRoutes = [];
    }
    for (const route of hiddenRoutes) {
      routes.push({
        source: route,
        headers: [
          {
            key: "X-Robots-Tag",
            value: "noindex, nofollow",
          },
        ],
      });
    }

    return routes;
  },
};

export default nextConfig;
